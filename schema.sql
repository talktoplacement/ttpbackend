-- TalktoPlacement / CareerPlatform — PRODUCTION schema for Supabase (PostgreSQL)
--
-- SINGLE SOURCE OF TRUTH for the database schema. This file is hand-maintained:
-- there are intentionally NO EF Core migration files in the project, and the API
-- never calls Database.MigrateAsync(). To add or change a column/table/index,
-- edit THIS file and re-apply it.
--
-- Run:  Supabase SQL Editor -> paste -> Run   |   psql "$DB_URL" -f schema.sql
--
-- Idempotency: every statement is natively re-runnable
-- (CREATE TABLE/INDEX IF NOT EXISTS, ADD COLUMN IF NOT EXISTS), so applying the
-- file repeatedly is a no-op and newly-added statements are picked up on the next
-- run. Do NOT reintroduce a migration-history gate — it would silently skip new
-- statements on databases that already recorded the migration id.
--
-- The whole file runs in one transaction: either the entire schema applies or
-- nothing does.
--
-- The .NET API connects as table owner (postgres) and BYPASSES the RLS below,
-- which only locks down Supabase's auto PostgREST/anon data API.
-- =============================================================================

