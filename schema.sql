-- =============================================================================
-- Coding-assessment engine (LeetCode-style attempts)
--
-- Adds structured questions, test cases, and per-question attempt answers so that
-- scoring can happen SERVER-SIDE. The pre-existing Assessments.QuestionsJson blob
-- is left untouched for backwards compatibility, but the runner reads from these
-- tables: an opaque JSON blob cannot express hidden test cases, and a client-
-- supplied score can never be trusted.
-- =============================================================================

-- One question within an assessment. Supports multiple-choice and coding types;
-- the type-specific columns are nullable because only one family applies at a time.
CREATE TABLE IF NOT EXISTS "AssessmentQuestions" (
    "Id"                integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "AssessmentId"      integer NOT NULL,
    "OrderIndex"        integer NOT NULL DEFAULT 0,
    -- 'mcq' | 'coding'
    "QuestionType"      character varying(16) NOT NULL,
    "Title"             character varying(300) NOT NULL,
    "PromptMarkdown"    text NOT NULL DEFAULT '',
    "Marks"             integer NOT NULL DEFAULT 1,
    -- MCQ: JSON array of option strings, plus the zero-based index of the answer.
    -- CorrectOptionIndex is never projected to a student-facing response.
    "OptionsJson"       text,
    "CorrectOptionIndex" integer,
    -- Coding: the function the student must implement and per-language starter code
    -- as a JSON object keyed by language id, e.g. {"python":"def solve(...):"}.
    "FunctionName"      character varying(128),
